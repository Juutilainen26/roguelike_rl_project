# -----------------------------------------------------------------------------
# [1] 변수(variable): 값에 '이름'을 붙여 저장해 두는 것.
#     한 번 정해두면 나중에 이름만 바꿔도 전체가 바뀌어 편리하다.
# -----------------------------------------------------------------------------
WIDTH = 11    # 맵의 가로 칸 수
HEIGHT = 7    # 맵의 세로 칸 수

# 맵을 그릴 때 쓸 글자들도 변수로 정해두면 나중에 한 곳만 고쳐도 된다.
WALL = "#"     # 벽 (지나갈 수 없는 곳)
FLOOR = "."    # 바닥 (지나갈 수 있는 곳)
PLAYER = "@"   # 플레이어 (나)
EXIT = "E"     # 출구 (다음 층으로 가는 곳)


# -----------------------------------------------------------------------------
# [2] 함수(function): 여러 줄짜리 작업에 '이름'을 붙여 재사용하는 것.
#     'def 이름(재료):' 형태로 만들고, 필요할 때 이름을 불러 사용한다.
# -----------------------------------------------------------------------------
def make_map(width, height):
    """가로 width, 세로 height 크기의 맵을 만들어서 돌려준다.
    맵은 '리스트 안에 리스트'(2차원 리스트)로 표현한다."""

    # [3] 리스트(list): 여러 값을 순서대로 담는 상자. 대괄호 [] 로 만든다.
    #     grid 는 '한 줄(row)'들을 담는 바깥 리스트다.
    grid = []

    # [4] 반복문(for): 정해진 횟수만큼 같은 작업을 반복한다.
    #     range(height) 는 0, 1, 2, ... height-1 을 차례로 준다.
    for y in range(height):          # 세로(위->아래) 방향으로 한 줄씩
        row = []                     # 이번 줄에 들어갈 칸들을 담을 리스트
        for x in range(width):       # 가로(왼->오른) 방향으로 한 칸씩
            # [5] 조건문(if): 상황에 따라 다른 값을 고른다.
            #     맨 바깥 테두리(첫 줄/끝 줄/첫 칸/끝 칸)는 벽으로 만든다.
            if x == 0 or x == width - 1 or y == 0 or y == height - 1:
                row.append(WALL)     # append: 리스트 끝에 값을 추가한다
            else:
                row.append(FLOOR)    # 안쪽은 바닥
        grid.append(row)             # 완성된 한 줄을 맵(grid)에 추가

    return grid                      # 다 만든 맵을 돌려준다


def place(grid, x, y, symbol):
    """맵의 (x, y) 위치에 원하는 글자(symbol)를 놓는다."""
    # grid[y][x] : y번째 줄의 x번째 칸.
    # 순서 주의! 세로(y)가 먼저, 가로(x)가 나중이다.
    grid[y][x] = symbol


def print_map(grid):
    """맵(2차원 리스트)을 화면에 글자로 출력한다."""
    for row in grid:                 # 한 줄(row)씩 꺼내서
        # "".join(row) : 리스트 안의 글자들을 하나의 문자열로 이어붙인다.
        print("".join(row))


# -----------------------------------------------------------------------------
# 아래는 '이 파일을 직접 실행했을 때만' 동작하는 부분이다.
# (다른 파일에서 이 코드를 가져다 쓸 때는 실행되지 않게 하는 Python 관용 표현)
# -----------------------------------------------------------------------------
if __name__ == "__main__":
    game_map = make_map(WIDTH, HEIGHT)          # 1) 맵 만들기

    # 2) 플레이어를 왼쪽 위 근처(1,1)에, 출구를 오른쪽 아래 근처에 놓는다.
    place(game_map, 1, 1, PLAYER)
    place(game_map, WIDTH - 2, HEIGHT - 2, EXIT)

    print_map(game_map)                         # 3) 화면에 출력
