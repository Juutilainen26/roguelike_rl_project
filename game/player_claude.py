#
# 이번에 배우는 것:
#   - 다른 파일 가져오기(import)  : 1주차 map.py의 함수를 재사용한다
#   - while 반복문                : "끝날 때까지 계속" 반복하는 방법
#   - 키 입력 받기(input)         : 사용자가 누른 키로 캐릭터를 움직인다
#   - 벽 충돌 처리                : 벽이면 못 가게 막는다
#   - 체력(HP) 개념               : 상태 값을 화면에 표시한다 (전투는 3주차)
#
# 실행 방법: 터미널에서   python game/player_claude.py
#   (이동: w=위, s=아래, a=왼쪽, d=오른쪽 / 종료: q)  각 키를 누르고 Enter
# =============================================================================


# -----------------------------------------------------------------------------
# [import] 1주차에 만든 map.py 안의 도구들을 그대로 가져와 재사용한다.
#   같은 game 폴더 안에 있으므로 'import map' 으로 불러올 수 있다.
#   ※ map.py 의 맨 아래 'if __name__ == "__main__"' 덕분에,
#     import 할 때는 그 안의 실행 코드가 자동으로 돌지 않는다. (1주차에 배운 것)
# -----------------------------------------------------------------------------
import map   # map.py 파일을 가져온다


def draw(game_map, px, py, hp):
    """현재 상태(플레이어 위치 px,py 와 체력 hp)를 화면에 그린다."""
    # 맵을 '매번 새로' 만든다. 이렇게 하면 플레이어가 지나간 자리에
    # @ 자국이 남지 않는다. (이전 위치를 지우는 대신 깨끗한 맵을 다시 그림)
    fresh = map.make_map(map.WIDTH, map.HEIGHT)

    # 출구와 플레이어를 새 맵 위에 올린다. (map.py의 place 함수 재사용)
    map.place(fresh, map.WIDTH - 2, map.HEIGHT - 2, map.EXIT)
    map.place(fresh, px, py, map.PLAYER)

    print("=" * (map.WIDTH))     # 위쪽 구분선
    map.print_map(fresh)         # 맵 출력 (map.py의 함수 재사용)
    print(f"체력(HP): {hp}   이동: w/a/s/d,  종료: q")   # 상태 표시줄


# -----------------------------------------------------------------------------
# 아래는 이 파일을 직접 실행할 때만 도는 부분 (map.py에서 배운 관용 표현)
# -----------------------------------------------------------------------------
if __name__ == "__main__":
    # [상태 변수] 플레이어의 현재 위치와 체력. 게임이 도는 동안 값이 바뀐다.
    px, py = 1, 1     # 시작 위치 (가로 x=1, 세로 y=1)  → 1주차와 동일
    hp = 10           # 체력. 지금은 표시만 한다. (적/전투는 3주차에 추가)

    # 먼저 맵을 한 번 만들어 둔다. (벽 위치를 확인해 충돌 판정에 쓴다)
    game_map = map.make_map(map.WIDTH, map.HEIGHT)

    draw(game_map, px, py, hp)   # 시작 화면을 한 번 그린다

    # [while 반복문] '조건이 참인 동안' 계속 반복한다.
    #   여기서는 True(항상 참)로 두고, 안에서 break 로 빠져나온다.
    while True:
        key = input("어디로 갈까요? > ")   # 사용자 입력을 받는다 (Enter까지 기다림)

        # 종료 키
        if key == "q":
            print("게임을 종료합니다.")
            break                         # while 반복문 탈출

        # [이동 계산] 먼저 '가려는 위치'를 계산만 해 둔다. (아직 실제 이동 X)
        #   nx, ny = 다음(next) 위치
        nx, ny = px, py
        if key == "w":
            ny = py - 1     # 위로  → 세로가 1 줄어든다
        elif key == "s":
            ny = py + 1     # 아래로 → 세로가 1 늘어난다
        elif key == "a":
            nx = px - 1     # 왼쪽으로
        elif key == "d":
            nx = px + 1     # 오른쪽으로
        else:
            print("w, a, s, d, q 중에서 눌러주세요.")
            continue        # 이번 반복은 건너뛰고 다시 입력 받기

        # [벽 충돌 처리] 가려는 칸이 벽이면 이동하지 않는다.
        #   game_map[ny][nx] : 그 칸에 무엇이 있는지 확인 (세로 먼저, 가로 나중)
        if game_map[ny][nx] == map.WALL:
            print("벽이라 갈 수 없어요!")
        else:
            # 벽이 아니면 실제로 이동 (현재 위치를 다음 위치로 갱신)
            px, py = nx, ny

        # [승리 판정] 출구 위치에 도착하면 승리
        if px == map.WIDTH - 2 and py == map.HEIGHT - 2:
            draw(game_map, px, py, hp)
            print("출구에 도착했습니다! 🎉  (다음 단계: 다음 층으로 이동 — 4주차)")
            break

        draw(game_map, px, py, hp)   # 바뀐 상태로 다시 그리기
