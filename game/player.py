import map# import는 큰 범위, from은 그 안에서 하나. 여기서 map.py를 쓰면 map함수를 쓰면 된다.
# [답변] 정확해요! import map = map.py 통째로 가져오기(그래서 쓸 때 map.make_map 처럼 앞에 map. 필요).
#        from map import make_map = 필요한 것 하나만 콕 집어오기(그럼 map. 없이 make_map() 바로 사용).

def draw(game_map, px, py, hp):
    """현재 상태를 화면에 그린다."""
    # 선생님께서는 맵을 매번 새로 그린다고 했음, 개념이 잘 이해가 안되지만
    # 아마 이동을 했을때 이동한걸 한 프레임으로 다시 그리는걸 뜻하는듯 하다.
    # [답변] 추측이 맞아요! 매번 깨끗한 맵을 새로 만들고 바뀐 위치로 @를 다시 올려 "한 프레임"처럼 그림.
    #        안 그러면 @가 지나간 자리에 자국이 남음. (칠판 지우고 다시 그리기)
    fresh= map.make_map(map.WIDTH, map.HEIGHT)

    map.place(fresh, map.WIDTH-2, map.HEIGHT-2, map.EXIT)# 출구 표기
    map.place(fresh, px, py, map.PLAYER)# 플레이어 표기

    print("="*(map.WIDTH))# =를 가로칸수만큼
    map.print_map(fresh)
    print(f"체력(HP): {hp} 이동 w/a/s/d, 종료: q")# 이게 써지는 위치는 지정을 안해줘도 되는건가?
    # [답변] 지정 안 해도 됨. print는 항상 "다음 줄"에 순서대로 찍힘. 맵을 먼저 print하고
    #        이걸 나중에 print했으니 자연히 맵 아래에 나옴. 위치가 아니라 '실행 순서'가 화면 순서를 정함.

#만든 함수가 제대로 동작하는지 자가 테스트
if __name__ == "__main__":
    px, py=1, 1# x좌표 y좌표값 x1, x2, x3 = y1, y2, y3 이런식으로 1:1 매칭이 되는 문법인가?
    # [답변] 맞아요! 왼쪽 순서대로 오른쪽 값이 하나씩 짝지어 들어감 → px=1, py=1. 이름은 "여러 개 한 번에 대입".
    hp=10 # 위에 작성한 체력변수에 넣는값. 아직은 변동이 없다.

    game_map=map.make_map(map.WIDTH, map.HEIGHT)# 위에서 맵을 만드는데 왜 만들어 놓고 시작을 하는걸까?
    # [답변] 이 game_map은 '벽 위치 확인용'. 아래 45번 줄에서 game_map[ny][nx]==WALL 로 "거기 벽이야?"를 물어봄.
    #        벽 배치는 안 바뀌니 한 번만 만들어 두고 계속 참고. (draw 안의 fresh는 '화면 그리기용'이라 역할이 다름)

    draw(game_map, px, py, hp)# 그린다....주체랑 위치는 어디에서 설정?
    # [답변] 괄호 안에 넘겨준 값이 그 설정임. px,py가 위치, game_map이 그릴 맵. draw는 '받은 값대로 그리기만' 함.

    while True:# 아...무한 루프에 빠져서 프로그램 멈춘 트라우마가....
        key=input("어디로 갈까요? > ")# 일단 움직일건지 물어보고 시작한다는거지요?
        # [답변] 네. 반복이 한 바퀴 돌 때마다 여기서 멈춰 키를 기다림. 키를 줘야 다음으로 진행됨.

        if key == "q":# 만약 q값이 들어온다면
            print("게임을 종료합니다.")
            break# 꺼져!

        nx, ny=px, py# p는 현재 위치, n은 다음 위치
        if key=="w":
            ny=py-1# 위로. 화면상의 좌표는 0, 0이 좌측 상단 시작점이다.
        elif key=="s":
            ny=py+1# 아래로
        elif key=="a":
            nx=px-1# 왼쪽
        elif key=="d":
            nx=px+1# 오른쪽
        else:
            print("w, a, s, d, q 중에서 눌러주세요.")# 어문키를 눌렀을때 경고문
            continue# 처음보는거다. 어문키 눌렀을때 프린트 하고 if문을 다시 처음부터 시작하라는건듯
            # [답변] 거의 맞아요! 정확히는 "이번 한 바퀴는 여기서 끝, while 맨 위로 돌아가 다시 입력받기". (if가 아니라 while의 처음으로)

        if game_map[ny][nx]==map.WALL:# 어째서 nx, ny가 먼저 보는지 이해불가.
        # [답변] nx,ny는 '가려고 하는' 칸. 실제로 옮기기 전에 그 목적지가 벽인지 먼저 들여다보는 것. (한 발 딛기 전 앞을 봄)
            print("벽이라 갈 수 없어요!")# 기억하자 열y 먼저 x행 나중에 자꾸 잊어
        else:
            px, py=nx,ny#벽이 아니라면. 그런데 벽이라고 갈 수 없다고 말만하고 실제로 이동 불가 판정은 없는거 아닌가?
            # 아니면 px,py에 실제 이동값을 주지 않기 때문에 이동하지 않는다고 보는건가?
            # [답변] 두 번째 추측이 정확해요! 벽일 땐 px,py를 안 바꿈 → 위치 그대로 → 제자리. 즉 '막는 코드'가 따로 있는 게
            #        아니라 "이동시키지 않음 = 못 감". 스스로 답을 찾으셨어요!
        if px==map.WIDTH-2 and py==map.HEIGHT-2:#and는 둘다 만족시
            draw(game_map, px, py, hp)# 현재 위치를 다시 그림(어떻게?)
            # [답변] draw에 지금 px,py를 넘기면, draw가 그 위치로 @를 올린 새 화면을 그려줌(위 draw 함수가 하는 일).
            print("출구에 도착했습니다! 아직 끝나지 않았습니다! 정신줄 놓지 마세요!")
            break# 이걸 if문 안에 써도 while문에서 동작하는 거라 상관 없는건가?
            # [답변] 상관없어요. break는 자기를 감싼 '가장 가까운 반복문(while)'을 빠져나감. if 안에 있어도 while을 끊음.
        
        draw(game_map, px, py, hp)# 두번째 if문에서 움직인걸 그리는 건가?
        # [답변] 맞아요. 벽 판정과 승리 판정을 다 거친 뒤, 최종으로 바뀐 위치(px,py)로 화면을 다시 그리는 마무리.